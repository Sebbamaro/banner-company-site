CREATE TABLE IF NOT EXISTS leads (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 created_at DATETIME NOT NULL, name VARCHAR(100) NOT NULL, phone VARCHAR(12) NOT NULL,
 comment TEXT NOT NULL, page VARCHAR(255) NOT NULL, utm TEXT NOT NULL,
 consent_at DATETIME NOT NULL, consent_version VARCHAR(80) NOT NULL,
 email_status VARCHAR(20) NOT NULL DEFAULT 'pending', telegram_status VARCHAR(20) NOT NULL DEFAULT 'pending',
 email_attempts INT NOT NULL DEFAULT 0, telegram_attempts INT NOT NULL DEFAULT 0,
 INDEX(created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS jobs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, lead_id BIGINT UNSIGNED NOT NULL,
 channel VARCHAR(12) NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'pending', attempts INT NOT NULL DEFAULT 0,
 available_at DATETIME NOT NULL, error_code VARCHAR(40) NULL,
 UNIQUE KEY(lead_id,channel), INDEX(status,available_at),
 FOREIGN KEY(lead_id) REFERENCES leads(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rate_limits (
 key_hash CHAR(64) PRIMARY KEY, window_start BIGINT NOT NULL, hits INT NOT NULL
) ENGINE=InnoDB;
